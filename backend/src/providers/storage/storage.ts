export interface StoredObject {
  data: Buffer;
  contentType: string;
}

/**
 * Where uploaded files live. Callers only deal in opaque keys such as
 * `avatars/<random>.webp`; swapping local disk for an S3-compatible bucket later means adding
 * one implementation, not touching the services that use it.
 */
export interface StorageProvider {
  put(key: string, data: Buffer, contentType: string): Promise<void>;
  /** Returns null when the object does not exist. */
  get(key: string): Promise<StoredObject | null>;
  /** Succeeds silently when the object does not exist. */
  delete(key: string): Promise<void>;
}

// Keys are always generated by the server; anything else is rejected outright so a key can
// never be used for path traversal.
const KEY_PATTERN = /^[a-z0-9-]+\/[A-Za-z0-9_-]+\.[a-z0-9]+$/;

export function assertValidKey(key: string): void {
  if (!KEY_PATTERN.test(key)) throw new Error('Invalid storage key');
}
